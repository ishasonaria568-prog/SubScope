/**
 * Validates and normalizes candidate subdomain labels.
 * Strips whitespace, converts to lowercase, rejects invalid symbols.
 */
export function sanitizeWordlist(input: string | string[], maxLimit = 500): string[] {
  let list: string[] = [];

  if (typeof input === 'string') {
    list = input.split(/[\r\n,;\s]+/);
  } else if (Array.isArray(input)) {
    list = input;
  }

  const labelRegex = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/;
  const unique = new Set<string>();

  for (const item of list) {
    if (unique.size >= maxLimit) break;
    const clean = item.trim().toLowerCase();
    if (!clean) continue;
    // Allow standard subdomain label syntax
    if (labelRegex.test(clean) && clean.length <= 63) {
      unique.add(clean);
    }
  }

  return Array.from(unique);
}
